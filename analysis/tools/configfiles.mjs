import fs from "node:fs";
const t = fs.readFileSync(process.argv[2], "utf8");
const re = /configDir\s*\+\s*"\/"\s*\+\s*([A-Za-z0-9_$.]+)/g;
let m;
const seen = new Set();
while ((m = re.exec(t))) seen.add(m[1]);
console.log("expr:", [...seen].join(", "));
